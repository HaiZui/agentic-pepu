// Regenerates web/src/api/openapi.json (from the backend models) and web/src/api/schema.d.ts.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(webRoot, "..");
export const openapiPath = join(webRoot, "src", "api", "openapi.json");
export const schemaPath = join(webRoot, "src", "api", "schema.d.ts");

const HEADER = "// Generated by `npm run gen:api` from src/api/openapi.json. Do not edit.\n";

export async function generateTypes(openapiJsonText) {
  const ast = await openapiTS(JSON.parse(openapiJsonText));
  return HEADER + astToString(ast);
}

function pythonExecutable() {
  const venvPython = process.platform === "win32"
    ? join(repoRoot, ".venv", "Scripts", "python.exe")
    : join(repoRoot, ".venv", "bin", "python");
  return existsSync(venvPython) ? venvPython : "python";
}

async function main() {
  execFileSync(pythonExecutable(), ["-m", "bottle_throne", "dump-openapi", openapiPath], {
    cwd: repoRoot,
    stdio: "inherit",
  });
  const types = await generateTypes(readFileSync(openapiPath, "utf-8"));
  writeFileSync(schemaPath, types, "utf-8");
  console.log(`Wrote ${schemaPath}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
